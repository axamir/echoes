#!/usr/bin/env python3
"""Build the Mermaid interaction maps in diagrams/ from the archive data.

Inputs (read only): data/emails.json, data/official_announcements.json, docs/emails-text/ (via threads.py).
Outputs (overwritten on each run):
  diagrams/thread-map.md      Echo1..Echo7 threads grouped by folder and subject, linked by shared subject / Case ID
  diagrams/case-map.md        Case IDs -> archive folders / PDFs, first/last message, message counts
  diagrams/handover-flow.md   Echo-to-Echo transitions that are stated explicitly in the message text
  diagrams/timeline-gantt.md  Gantt chart: thread activity vs dated official announcements

Rules (mechanical, no inference):
- A "thread group" is all PDFs with the same Echo folder, archive Case ID folder and subject (subject with any
  leading "Case Id <ID>" / "Case Number <ID>" removed). Dates are the first and last message header timestamps
  printed inside those PDFs (threads.parse_thread), not filename dates.
- "Occurrences" counts every message header in the PDFs (duplicates included); "unique" counts distinct messages
  using the same key as threads.unique_messages() (sender address, timestamp, n).
- Handover edges are drawn only where a message body contains an explicit transition between two Echo labels:
  an arrow ("Echo 2 → Echo 3"), "handover from Echo X to Echo Y", "from Echo X through Echo Y" or
  "between Echo X and the emerging Echo Y". Ranges such as "Echo 1 to Echo 6.2" are not treated as transitions.
  Each edge cites the earliest de-duplicated message that states it.
- Timestamps carry no timezone in the source; none is assumed.
Standard library only.
"""
import json, re, sys
from collections import OrderedDict, defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import threads  # noqa: E402

ROOT = threads.ROOT
OUT = ROOT / "diagrams"
CASE_RE = re.compile(r"\b500VU[0-9A-Za-z]{10}(?:[0-9A-Za-z]{3})?\b")
GEN = "Generated by [`analysis/scripts/build_diagrams.py`](../analysis/scripts/build_diagrams.py); do not edit by hand. Regenerate with `python3 analysis/scripts/build_diagrams.py`."


def esc(s):
    """Text safe inside a quoted Mermaid flowchart label."""
    return (s.replace("&", "&amp;").replace('"', "#quot;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("[", "(").replace("]", ")").replace("{", "(").replace("}", ")"))


def norm_subject(r):
    s = r["subject"]
    if r["case_id"]:
        s = re.sub(r"^(Case Id|Case Number)\s+" + re.escape(r["case_id"]) + r"\s*", "", s)
    return s.strip()


def rel(p):
    return "../" + p


def day(ts):
    return ts[:10]


def load():
    recs = threads.load_records()
    msgs = {}
    for r in recs:
        ms = threads.parse_thread(r["text_file"])
        for m in ms:
            m["thread_id"] = r["id"]
        msgs[r["id"]] = ms
    return recs, msgs


BROADCAST_MIN = 5  # a message from Amir whose opening is identical in at least this many thread groups is a broadcast


def fp(m):
    """Fingerprint for broadcast detection: sender side + first 200 characters of the whitespace-normalised body."""
    return (m["side"], re.sub(r"\s+", " ", m["body"]).strip()[:200])


BROADCAST = set()


def thread_groups(recs, msgs):
    groups = OrderedDict()
    sha_groups = defaultdict(set)
    for r in recs:
        for m in msgs[r["id"]]:
            if m["side"] == "amir" and m["body"].strip():
                sha_groups[fp(m)].add((r["echo_label"], r["archive_case_folder"], norm_subject(r)))
    broadcast = {h for h, gs in sha_groups.items() if len(gs) >= BROADCAST_MIN}
    BROADCAST.update(broadcast)
    for r in recs:
        k = (r["echo_label"], r["archive_case_folder"], norm_subject(r))
        g = groups.setdefault(k, {"echo": k[0], "folder": k[1], "subject": k[2], "records": [],
                                  "case_ids": [], "keys": set(), "occ": 0, "ts": [], "ts_nb": [], "bc": []})
        g["records"].append(r)
        if r["case_id"] and r["case_id"] not in g["case_ids"]:
            g["case_ids"].append(r["case_id"])
        for m in msgs[r["id"]]:
            g["occ"] += 1; g["keys"].add(m["key"]); g["ts"].append(m["ts"])
            if fp(m) in broadcast:
                g["bc"].append((m["ts"], m["body"].splitlines()[0][:120]))
            else:
                g["ts_nb"].append(m["ts"])
    out = sorted(groups.values(), key=lambda g: (min(g["ts"]), g["echo"]))
    for i, g in enumerate(out, 1):
        g["n"] = i; g["id"] = f"T{i}"; g["first"] = min(g["ts"]); g["last"] = max(g["ts"])
        g["pdfs"] = len(g["records"]); g["unique"] = len(g["keys"])
        g["last_nb"] = max(g["ts_nb"])
        g["sha_dupes"] = len(g["records"]) - len({r["sha256"] for r in g["records"]})
    return out


def write(name, text):
    (OUT / name).write_text(text, encoding="utf-8")
    print("wrote", OUT / name)


