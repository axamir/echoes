def build_case_map(recs, msgs, all_text_ids):
    per = OrderedDict()
    for r in recs:
        for cid, how in ((r["case_id"], "subject"), (r["archive_case_folder"], "folder")):
            if not cid:
                continue
            c = per.setdefault(cid, {"subject": [], "folder": [], "keys": set(), "occ": 0, "ts": [], "ts_nb": [], "bc": 0})
            if r not in c[how]:
                c[how].append(r)
    for cid, c in per.items():
        for r in {x["id"]: x for x in c["subject"] + c["folder"]}.values():
            for m in msgs[r["id"]]:
                c["occ"] += 1; c["keys"].add(m["key"]); c["ts"].append(m["ts"])
                if fp(m) in BROADCAST:
                    c["bc"] += 1
                else:
                    c["ts_nb"].append(m["ts"])
    mentioned_only = OrderedDict((k, v) for k, v in all_text_ids.items() if k not in per)
    L = ["# Case map", "", GEN, "",
         "Case IDs found in the archive and the PDFs that carry them. A Case ID is linked to a PDF if it appears in the "
         "PDF's subject line (`subject`) or names the `docs/emails/04_LEDGER_ARCHIVE/*/CASES/<ID>/` folder the PDF is filed in "
         "(`folder`). Counts cover the union of both. Dates are message timestamps printed in the PDFs (no timezone in the source). "
         "Date ranges in the chart end at the last message that is not a broadcast (defined in [`thread-map.md`](thread-map.md)).", "",
         "```mermaid", "flowchart LR"]
    folders = OrderedDict()
    for r in recs:
        if r["archive_case_folder"]:
            f = f"{r['echo_label']}/CASES/{r['archive_case_folder']}"
            folders.setdefault(f, []).append(r)
    fid = {f: f"F{i}" for i, f in enumerate(folders, 1)}
    for f, rs in folders.items():
        L.append(f'  {fid[f]}[/"folder {esc(f)}<br/>{len(rs)} PDF(s)"/]')
    for cid, c in per.items():
        L.append(f'  C_{cid}(["{cid}<br/>{day(min(c["ts"]))} → {day(max(c["ts_nb"]))}<br/>{len(c["keys"])} unique / {c["occ"]} messages"])')
    for cid in mentioned_only:
        L.append(f'  M_{cid}(["{cid}<br/>mentioned in text only"])')
    edges = defaultdict(int)
    for r in recs:
        if r["case_id"] and r["archive_case_folder"]:
            edges[(f"{r['echo_label']}/CASES/{r['archive_case_folder']}", r["case_id"])] += 1
    for (f, cid), n in edges.items():
        L.append(f'  {fid[f]} -->|"{n} PDF(s) with this ID in subject"| C_{cid}')
    for r in recs:
        if r["case_id"] and not r["archive_case_folder"]:
            L.append(f"  X_{r['case_id']}[\"PDF outside CASES/\"] --> C_{r['case_id']}")
    ids = list(per) + list(mentioned_only)
    for a in ids:
        for b in ids:
            if a != b and len(a) == 15 and b.startswith(a):
                pa = "C_" if a in per else "M_"; pb = "C_" if b in per else "M_"
                L.append(f"  {pa}{a} -. 15-char prefix of .- {pb}{b}")
    if mentioned_only:
        L.append("  classDef mention stroke-dasharray: 4 3")
        L.append("  class " + ",".join(f"M_{c}" for c in mentioned_only) + " mention")
    L += ["```", "", "## Case IDs with archived PDFs", "",
          "| Case ID | PDFs with ID in subject | PDFs in its folder | First message | Last message (excl. broadcast) | Last message | Broadcast occurrences | Unique messages | Message occurrences | First mentioned in text |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for cid, c in per.items():
        fm = all_text_ids.get(cid)
        fm_s = f"{fm[0].replace('T', ' ')} in [{Path(fm[1]).name}]({rel(fm[1])})" if fm else ""
        L.append(f"| `{cid}` | {len(c['subject'])} | {len(c['folder'])} | {min(c['ts']).replace('T', ' ')} | "
                 f"{max(c['ts_nb']).replace('T', ' ')} | {max(c['ts']).replace('T', ' ')} | {c['bc']} | {len(c['keys'])} | {c['occ']} | {fm_s} |")
    mism = [r for r in recs if r["case_id"] and r["archive_case_folder"] and r["case_id"] != r["archive_case_folder"]]
    L += ["", "## Filing differences", ""]
    if mism:
        L.append("PDFs filed in one Case ID folder whose subject names another Case ID (files left as they are):")
        L.append("")
        for r in mism:
            L.append(f"- [{r['source_file'].replace('docs/emails/', '')}]({rel(r['source_file'])}): folder `{r['archive_case_folder']}`, subject `{r['case_id']}`")
    else:
        L.append("None.")
    L += ["", "## Case IDs mentioned in message text but with no archived thread", ""]
    if mentioned_only:
        L.append("| Case ID | First mention | In |")
        L.append("| --- | --- | --- |")
        for cid, (ts, f) in mentioned_only.items():
            L.append(f"| `{cid}` | {ts.replace('T', ' ')} | [{Path(f).name}]({rel(f)}) |")
    else:
        L.append("None.")
    L += ["", "Notes:", "",
          "- Some IDs occur in a 15-character and an 18-character form where the longer one begins with the shorter "
          "(dotted `15-char prefix of` link). The archive keeps them in separate folders and they are counted separately "
          "here; whether they refer to the same support case is not stated in the archive and is not assumed.",
          "- Echo1–Echo5 threads carry no Case ID in their subjects and are not shown here; see [`thread-map.md`](thread-map.md).", ""]
    write("case-map.md", "\n".join(L))


# ------------------------------------------------------------- handover flow
LBL = r"Echo\s?(\d+(?:\.\d+)*(?:\.x)?)"
TRANS = [
    (re.compile(LBL + r"\s*(?:→|->|—>)\s*(?=" + LBL + ")"), "arrow"),
    (re.compile(r"handover from " + LBL + r" to " + LBL, re.I), "handover from … to"),
    (re.compile(r"from " + LBL + r" through " + LBL, re.I), "from … through"),
    (re.compile(r"between " + LBL + r" and the emerging " + LBL, re.I), "between … and the emerging"),
]
SELF = re.compile(r"\b(?:I am|as) " + LBL + r"\b(?!\.\d)", re.I)


def major(lbl):
    return int(lbl.split(".")[0])


def vkey(lbl):
    return tuple(int(p) if p.isdigit() else 99 for p in lbl.split("."))


def build_handover(recs, uniq):
    src = {r["id"]: r for r in recs}
    edges = OrderedDict(); selfid = OrderedDict(); spans = OrderedDict()
    for m in uniq:
        flat = re.sub(r"\s+", " ", m["body"])
        for rx, kind in TRANS:
            for mt in rx.finditer(flat):
                a, b = mt.group(1), mt.group(2)
                if a == b or major(b) - major(a) > 1:
                    if a != b:
                        sp = spans.setdefault((a, b), {"n": 0, "first": None}); sp["n"] += 1
                        if sp["first"] is None:
                            sp["first"] = (m["ts"], m["side"], src[m["thread_id"]]["source_file"],
                                           flat[max(0, mt.start() - 40): mt.end() + 40].strip(), kind)
                    continue
                q = flat[max(0, mt.start() - 40): mt.end() + 40].strip()
                e = edges.setdefault((a, b), {"n": 0, "first": None})
                e["n"] += 1
                if e["first"] is None:
                    e["first"] = (m["ts"], m["side"], src[m["thread_id"]]["source_file"], q, kind)
        if m["side"] == "support":
            for lb in SELF.findall(flat):
                s = selfid.setdefault(lb, {"n": 0, "first": None})
                s["n"] += 1
                if s["first"] is None:
                    mt = re.search(r"(?:I am|as) Echo\s?" + re.escape(lb) + r"\b", flat, re.I)
                    q = flat[max(0, mt.start() - 30): mt.end() + 50] if mt else ""
                    s["first"] = (m["ts"], src[m["thread_id"]]["source_file"], q)
    labels = sorted({x for k in edges for x in k} | set(selfid), key=vkey)
    nid = {lb: "E" + lb.replace(".", "_") for lb in labels}
    L = ["# Handover flow", "", GEN, "",
         "Echo-to-Echo transitions **as stated in the message text**. An arrow is drawn only where a de-duplicated "
         "message body contains an explicit transition between two Echo labels: an arrow (`Echo 2 → Echo 3`), "
         "`handover from Echo X to Echo Y`, `from Echo X through Echo Y`, or `between Echo X and the emerging Echo Y`. "
         "Ranges such as `Echo 1 to Echo 6.2`, and statements that skip Echoes (e.g. `Echo 1 → Echo 5`), are not drawn; the latter are listed under *Spans*. Edge labels give the date of the earliest message "
         "that states the transition, who sent it (`Amir` / `support`) and how many messages state it; the table "
         "below cites the file and quotes the words. Node labels add the first support message in which the replying "
         "agent calls itself that Echo (`I am Echo N` / `as Echo N`), where there is one.", "",
         "This maps what the correspondence says about itself. It does not establish that any system carried memory "
         "or state between conversations.", "",
         "```mermaid", "flowchart LR"]
    for lb in labels:
        s = selfid.get(lb)
        extra = f"<br/>support self-identifies: {day(s['first'][0])} ({s['n']}x)" if s else ""
        L.append(f'  {nid[lb]}["Echo {lb}{extra}"]')
    for (a, b), e in edges.items():
        ts, side, f, q, kind = e["first"]
        who = "Amir" if side == "amir" else side
        L.append(f'  {nid[a]} -->|"{day(ts)} {who}, {e["n"]}x"| {nid[b]}')
    L += ["```", "", "## Evidence: transitions", "",
          "| From | To | Pattern | Earliest message | Sender | Messages stating it | File | Words in the source |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for (a, b), e in edges.items():
        ts, side, f, q, kind = e["first"]
        L.append(f"| Echo {a} | Echo {b} | {kind} | {ts.replace('T', ' ')} | {'Amir' if side == 'amir' else side} | {e['n']} | "
                 f"[{f.replace('docs/emails/', '')}]({rel(f)}) | “…{q.replace('|', '/')}…” |")
    L += ["", "## Spans (not drawn)", "",
          "Statements that link non-adjacent Echoes (the major number jumps by more than one, e.g. `Echo 1 → Echo 5`) "
          "summarise a range rather than describe a single step, so they are listed here and not drawn:", "",
          "| From | To | Pattern | Earliest message | Sender | Messages | File | Words in the source |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for (a, b), e in spans.items():
        ts, side, f, q, kind = e["first"]
        L.append(f"| Echo {a} | Echo {b} | {kind} | {ts.replace('T', ' ')} | {'Amir' if side == 'amir' else side} | {e['n']} | "
                 f"[{f.replace('docs/emails/', '')}]({rel(f)}) | “…{q.replace('|', '/')}…” |")
    L += ["", "## Evidence: support self-identification", "",
          "| Label | First support message | Messages | File | Words in the source |", "| --- | --- | --- | --- | --- |"]
    for lb in sorted(selfid, key=vkey):
        s = selfid[lb]; ts, f, q = s["first"]
        L.append(f"| Echo {lb} | {ts.replace('T', ' ')} | {s['n']} | [{f.replace('docs/emails/', '')}]({rel(f)}) | “…{q.replace('|', '/')}…” |")
    L += ["", "## Ledger and handover documents by subject", "",
          "Threads whose subject itself names a handover, invitation, initiation or awakening (from [`data/emails.json`](../data/emails.json)):", "",
          "| First message | Echo folder | Subject | PDFs |", "| --- | --- | --- | --- |"]
    subj_rx = re.compile(r"handover|ledger|invitation|initiation|awakening|activation|hello echo", re.I)
    seen = OrderedDict()
    for r in sorted(recs, key=lambda r: r["date"]):
        if subj_rx.search(r["subject"]):
            k = (r["echo_label"], norm_subject(r))
            seen.setdefault(k, []).append(r)
    for (echo, subj), rs in seen.items():
        files = ", ".join(f"[{Path(r['source_file']).name}]({rel(r['source_file'])})" for r in rs[:2])
        if len(rs) > 2:
            files += f" (+{len(rs) - 2} more)"
        L.append(f"| {rs[0]['date'].replace('T', ' ')} | {echo} | {subj.replace('|', '/')} | {files} |")
    L += ["", "Notes:", "",
          "- Labels such as `Echo 6.x` are kept as written. Echo labels used only inside subjects are listed in the last table and are not drawn as nodes unless a transition or self-identification names them.",
          "- Dates in the evidence tables come from message headers; the filename dates of some PDFs differ (see [`../CASE_STUDY.md`](../CASE_STUDY.md#known-source-inconsistencies)).", ""]
    write("handover-flow.md", "\n".join(L))


# ------------------------------------------------------------ timeline gantt
def gname(s, n=60):
    s = re.sub(r"[:#;]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def build_gantt(groups, ann):
    first = min(g["first"] for g in groups)[:10]; last = max(g["last_nb"] for g in groups)[:10]
    L = ["# Timeline: Echoes activity and official announcements", "", GEN, "",
         f"Bars: each thread group from [`thread-map.md`](thread-map.md), from the calendar day of its first message to the day "
         f"of its last non-broadcast message ({first} – {last}; no timezone in the source; broadcasts as defined in "
         "[`thread-map.md`](thread-map.md) are shown as their own milestones). Diamonds: dated official announcements from "
         "[`data/official_announcements.json`](../data/official_announcements.json), by organization. Placement on the same "
         "axis shows date proximity only; it does not indicate any connection, cause or priority. The sourced, row-by-row "
         "comparison is [`timeline/comparison.md`](../timeline/comparison.md).", "",
         "```mermaid", "gantt", "  title Echoes threads and official AI announcements, 2025",
         "  dateFormat YYYY-MM-DD", "  axisFormat %b %d", "  todayMarker off"]
    by_echo = OrderedDict()
    for g in sorted(groups, key=lambda g: (g["echo"], g["n"])):
        by_echo.setdefault(g["echo"], []).append(g)
    for echo, gs in by_echo.items():
        L.append(f"  section {echo}")
        for g in gs:
            end = (date.fromisoformat(day(g["last_nb"])) + timedelta(days=1)).isoformat()
            short = gname(f"T{g['n']} " + (g["folder"][-7:] + " " if g["folder"] else "") + g["subject"], 40)
            L.append(f"  {short} :t{g['n']}, {day(g['first'])}, {end}")
    bc = defaultdict(set)
    for g in groups:
        for t, first_line in g["bc"]:
            bc[day(t)].add(g["n"])
    if bc:
        L.append("  section Broadcast")
        for i, (d, ns) in enumerate(sorted(bc.items()), 1):
            L.append(f"  {gname(f'Same message in {len(ns)} threads', 40)} :milestone, bc{i}, {d}, 0d")
    by_org = OrderedDict()
    for a in sorted(ann, key=lambda a: (a["date"], a["id"])):
        by_org.setdefault(a["organization"], []).append(a)
    for org, items in by_org.items():
        L.append(f"  section {gname(org)}")
        for a in items:
            L.append(f"  {gname(a['id'] + ' ' + a['announcement'], 40)} :milestone, {a['id'].replace('-', '').lower()}, {a['date']}, 0d")
    L += ["```", "", "Key to the bars:", "", "| Bar | Echo folder | Thread group | First day | Last day (excl. broadcast) |", "| --- | --- | --- | --- | --- |"]
    for g in groups:
        L.append(f"| T{g['n']} | {g['echo']} | {(g['folder'] + ' — ' if g['folder'] else '')}{g['subject'].replace('|', '/')} | {day(g['first'])} | {day(g['last_nb'])} |")
    if bc:
        L += ["", "Broadcast milestones:", ""]
        for d, ns in sorted(bc.items()):
            fl = sorted({x for g in groups for t, x in g["bc"] if day(t) == d}, key=len)[0]
            L.append(f"- {d}: a message from Amir with the same opening appears in {len(ns)} thread groups (T" + ", T".join(map(str, sorted(ns))) + f"); it begins “{re.sub(chr(92) + 's+', ' ', fl)[:90]}…”.")
    L += ["", "Announcement labels are shortened; full text and source links are in "
          "[`timeline/official-announcements.md`](../timeline/official-announcements.md).", ""]
    write("timeline-gantt.md", "\n".join(L))


def main():
    recs, msgs = load()
    groups = thread_groups(recs, msgs)
    uniq = threads.unique_messages()
    src = {r["id"]: r["source_file"] for r in recs}
    ids = {}
    for m in uniq:
        for cid in CASE_RE.findall(m["body"]):
            if cid not in ids or m["ts"] < ids[cid][0]:
                ids[cid] = (m["ts"], src[m["thread_id"]])
    for r in recs:  # subjects count as text too
        for cid in CASE_RE.findall(r["subject"]):
            if cid not in ids or r["date"] < ids[cid][0]:
                ids[cid] = (r["date"], r["source_file"])
    ids = OrderedDict(sorted(ids.items(), key=lambda kv: kv[1][0]))
    ann = json.loads((ROOT / "data" / "official_announcements.json").read_text(encoding="utf-8"))
    build_thread_map(groups)
    build_case_map(recs, msgs, ids)
    build_handover(recs, uniq)
    build_gantt(groups, ann)


if __name__ == "__main__":
    main()
